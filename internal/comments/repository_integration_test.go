func TestRepositoryListsCommentsRepliesAndChanges(t *testing.T) {
	pool := commentsTestPool(t)
	ctx := context.Background()
	base := time.Date(2026, 10, 17, 3, 0, 0, 0, time.UTC)
	for _, statement := range []string{
		`CREATE TABLE users (id text PRIMARY KEY, name text NOT NULL, avatar_url text)`,
		`CREATE TABLE comments (
			sid integer GENERATED BY DEFAULT AS IDENTITY, id text PRIMARY KEY,
			workspace_id text NOT NULL, doc_id text NOT NULL, user_id text NOT NULL,
			content jsonb NOT NULL, resolved boolean NOT NULL DEFAULT false,
			created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, deleted_at timestamptz
		)`,
		`CREATE TABLE replies (
			sid integer GENERATED BY DEFAULT AS IDENTITY, id text PRIMARY KEY,
			comment_id text NOT NULL, workspace_id text NOT NULL, doc_id text NOT NULL, user_id text NOT NULL,
			content jsonb NOT NULL, created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, deleted_at timestamptz
		)`,
	} {
		if _, err := pool.Exec(ctx, statement); err != nil {
			t.Fatalf("create comment fixture schema: %v", err)
		}
	}
	if _, err := pool.Exec(ctx, `INSERT INTO users(id,name,avatar_url) VALUES ('author-1','Author One','https://example.test/author.png'),('author-2','Author Two',NULL)`); err != nil {
		t.Fatalf("insert comment fixture users: %v", err)
	}
	if _, err := pool.Exec(ctx, `INSERT INTO comments(id,workspace_id,doc_id,user_id,content,resolved,created_at,updated_at,deleted_at)
		VALUES
		 ('comment-1','workspace-1','doc-1','author-1','{"text":"first"}',false,$1::timestamptz,$1::timestamptz,NULL),
		 ('comment-2','workspace-1','doc-1','author-2','{"text":"second"}',true,$1::timestamptz + interval '1 second',$1::timestamptz + interval '2 seconds',NULL),
		 ('comment-deleted','workspace-1','doc-1','author-1','{"text":"gone"}',false,$1::timestamptz,$1::timestamptz + interval '3 seconds',$1::timestamptz + interval '3 seconds'),
		 ('other-doc','workspace-1','doc-2','author-1','{"text":"other"}',false,$1::timestamptz,$1::timestamptz,NULL)`, base); err != nil {
		t.Fatalf("insert comment fixture comments: %v", err)
	}
	if _, err := pool.Exec(ctx, `INSERT INTO replies(id,comment_id,workspace_id,doc_id,user_id,content,created_at,updated_at,deleted_at)
		VALUES
		 ('reply-1','comment-1','workspace-1','doc-1','author-1','{"text":"first reply"}',$1::timestamptz + interval '4 seconds',$1::timestamptz + interval '4 seconds',NULL),
		 ('reply-2','comment-1','workspace-1','doc-1','author-2','{"text":"second reply"}',$1::timestamptz + interval '5 seconds',$1::timestamptz + interval '5 seconds',NULL),
		 ('reply-deleted','comment-1','workspace-1','doc-1','author-1','{"text":"gone"}',$1::timestamptz,$1::timestamptz + interval '6 seconds',$1::timestamptz + interval '6 seconds')`, base); err != nil {
		t.Fatalf("insert comment fixture replies: %v", err)
	}

	repository := NewRepository(pool)
	total, err := repository.Count(ctx, "workspace-1", "doc-1")
	if err != nil || total != 2 {
		t.Fatalf("comment count = %d, %v; want live comments only", total, err)
	}
	items, err := repository.List(ctx, "workspace-1", "doc-1", nil, 10)
	if err != nil || len(items) != 2 {
		t.Fatalf("comments = %#v, %v", items, err)
	}
	if items[0].ID != "comment-2" || !items[0].Resolved || items[1].ID != "comment-1" {
		t.Fatalf("comments not ordered by descending sid: %#v", items)
	}
	if items[1].User.Name != "Author One" || items[1].User.AvatarURL == nil || *items[1].User.AvatarURL != "https://example.test/author.png" {
		t.Fatalf("comment author projection = %+v", items[1].User)
	}
	if len(items[1].Replies) != 2 || items[1].Replies[0].ID != "reply-1" || items[1].Replies[1].ID != "reply-2" {
		t.Fatalf("replies not ordered by ascending sid or deleted reply leaked: %#v", items[1].Replies)
	}
	if items[1].Replies[0].User.ID != "author-1" || items[1].Replies[1].User.ID != "author-2" {
		t.Fatalf("reply author projection = %#v", items[1].Replies)
	}

	changes, err := repository.ListChanges(ctx, "workspace-1", "doc-1", nil, nil, 10)
	if err != nil || len(changes) != 6 {
		t.Fatalf("comment changes = %#v, %v; want 3 comment and 3 reply changes", changes, err)
	}
	if changes[0].ID != "comment-1" || changes[0].Action != "update" || changes[0].Item["workspaceId"] != "workspace-1" || changes[0].Item["docId"] != "doc-1" {
		t.Fatalf("comment change item does not preserve model fields: %#v", changes[0])
	}
	if changes[1].Action != "update" || changes[2].Action != "delete" || changes[2].Item["deletedAt"] == nil {
		t.Fatalf("comment change actions = %#v", changes[:3])
	}
	if changes[3].CommentID == nil || *changes[3].CommentID != "comment-1" || changes[3].Action != "update" || changes[4].Action != "update" || changes[5].Action != "delete" {
		t.Fatalf("reply change projection = %#v", changes[3:])
	}

	after := base.Add(2 * time.Second)
	changes, err = repository.ListChanges(ctx, "workspace-1", "doc-1", &after, &after, 10)
	if err != nil || len(changes) != 4 {
		t.Fatalf("changes after independent timestamps = %#v, %v", changes, err)
	}
}

func TestRepositoryWritesCommentsRepliesAndEnforcesPermissions(t *testing.T) {
	pool := commentsTestPool(t)
	ctx := context.Background()
	for _, statement := range []string{
		`CREATE TABLE users (id text PRIMARY KEY, name text NOT NULL, avatar_url text)`,
		`CREATE TABLE workspaces (id text PRIMARY KEY)`,
		`CREATE TABLE workspace_access_policies (workspace_id text PRIMARY KEY, sharing_enabled boolean NOT NULL DEFAULT true, member_default_doc_role text NOT NULL DEFAULT 'none')`,
		`CREATE TABLE workspace_members (workspace_id text NOT NULL, user_id text NOT NULL, role text NOT NULL, state text NOT NULL, updated_at timestamptz NOT NULL DEFAULT statement_timestamp())`,
		`CREATE TABLE workspace_sync_permission_generations (workspace_id text PRIMARY KEY, generation bigint NOT NULL DEFAULT 0)`,
		`CREATE TABLE doc_access_policies (workspace_id text NOT NULL, doc_id text NOT NULL, visibility text NOT NULL DEFAULT 'private', published_at timestamptz, public_role text, member_default_role text, PRIMARY KEY(workspace_id,doc_id))`,
		`CREATE TABLE doc_grants (workspace_id text NOT NULL, doc_id text NOT NULL, principal_type text NOT NULL, principal_id text NOT NULL, role text NOT NULL)`,
		`CREATE TABLE workspace_pages (workspace_id text NOT NULL, page_id text NOT NULL, published_at timestamptz)`,
		`CREATE TABLE entitlements (target_type text NOT NULL, target_id text NOT NULL, source text NOT NULL, plan text NOT NULL, quantity integer, starts_at timestamptz, status text NOT NULL, expires_at timestamptz, grace_until timestamptz)`,
		`CREATE TABLE comments (
			sid integer GENERATED BY DEFAULT AS IDENTITY, id text PRIMARY KEY,
			workspace_id text NOT NULL, doc_id text NOT NULL, user_id text NOT NULL,
			content jsonb NOT NULL, resolved boolean NOT NULL DEFAULT false,
			created_at timestamptz NOT NULL DEFAULT statement_timestamp(), updated_at timestamptz NOT NULL DEFAULT statement_timestamp(), deleted_at timestamptz
		)`,
		`CREATE TABLE replies (
			sid integer GENERATED BY DEFAULT AS IDENTITY, id text PRIMARY KEY,
			comment_id text NOT NULL, workspace_id text NOT NULL, doc_id text NOT NULL, user_id text NOT NULL,
			content jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT statement_timestamp(), updated_at timestamptz NOT NULL DEFAULT statement_timestamp(), deleted_at timestamptz
		)`,
	} {
		if _, err := pool.Exec(ctx, statement); err != nil {
			t.Fatalf("create comment write schema: %v", err)
		}
	}
	if _, err := pool.Exec(ctx, `
		INSERT INTO users(id,name) VALUES ('owner-1','Owner'),('author-1','Author One'),('author-2','Author Two');
		INSERT INTO workspaces(id) VALUES ('workspace-1');
		INSERT INTO workspace_access_policies(workspace_id,member_default_doc_role) VALUES ('workspace-1','none');
		INSERT INTO workspace_members(workspace_id,user_id,role,state) VALUES
			('workspace-1','owner-1','owner','active'),('workspace-1','author-1','member','active'),('workspace-1','author-2','member','active');
		INSERT INTO workspace_sync_permission_generations(workspace_id,generation) VALUES ('workspace-1',0);
		INSERT INTO doc_grants(workspace_id,doc_id,principal_type,principal_id,role) VALUES
			('workspace-1','doc-1','user','author-1','commenter'),('workspace-1','doc-1','user','author-2','reader');`); err != nil {
		t.Fatal(err)
	}
	authorizer := workspaces.NewAuthorizationService(workspaces.NewRepositoryWithDeployment(pool, "selfhosted"))
	repository := NewRepositoryWithAuthorizer(pool, authorizer)

	comment, err := repository.CreateComment(ctx, "author-1", "workspace-1", "doc-1", map[string]any{"text": "first"}, NotificationInput{})
	if err != nil || comment.ID == "" || comment.WorkspaceID != "workspace-1" || comment.DocID != "doc-1" || comment.User.ID != "author-1" || comment.Resolved || comment.Content["text"] != "first" {
		t.Fatalf("created comment = %+v, %v", comment, err)
	}
	if _, err := repository.CreateComment(ctx, "author-2", "workspace-1", "doc-1", map[string]any{"text": "denied"}, NotificationInput{}); !errors.Is(err, ErrCommentsCreateForbidden) {
		t.Fatalf("unauthorized comment create error = %v", err)
	}

	reply, err := repository.CreateReply(ctx, "author-1", comment.ID, map[string]any{"text": "reply"}, NotificationInput{})
	if err != nil || reply.ID == "" || reply.CommentID != comment.ID || reply.WorkspaceID != "workspace-1" || reply.DocID != "doc-1" || reply.User.ID != "author-1" {
		t.Fatalf("created reply = %+v, %v", reply, err)
	}
	if _, err := repository.UpdateComment(ctx, "author-1", comment.ID, map[string]any{"text": "edited"}); err != nil {
		t.Fatalf("comment owner update: %v", err)
	}
	if _, err := repository.ResolveComment(ctx, "author-1", comment.ID, true); err != nil {
		t.Fatalf("comment owner resolve: %v", err)
	}
	if _, err := repository.UpdateComment(ctx, "author-2", comment.ID, map[string]any{"text": "intrusion"}); !errors.Is(err, ErrCommentsModerateForbidden) {
		t.Fatalf("unauthorized comment update error = %v", err)
	}
	if _, err := repository.UpdateReply(ctx, "author-1", reply.ID, map[string]any{"text": "edited reply"}); err != nil {
		t.Fatalf("reply owner update: %v", err)
	}
	items, err := repository.List(ctx, "workspace-1", "doc-1", nil, 10)
	if err != nil || len(items) != 1 || items[0].Content["text"] != "edited" || !items[0].Resolved || len(items[0].Replies) != 1 || items[0].Replies[0].Content["text"] != "edited reply" {
		t.Fatalf("updated comment and reply projection = %#v, %v", items, err)
	}
	if _, err := repository.DeleteReply(ctx, "owner-1", reply.ID); err != nil {
		t.Fatalf("moderator reply delete: %v", err)
	}
	if _, err := repository.DeleteComment(ctx, "owner-1", comment.ID); err != nil {
		t.Fatalf("moderator comment delete: %v", err)
	}
	if _, err := repository.UpdateComment(ctx, "author-1", comment.ID, map[string]any{"text": "gone"}); !errors.Is(err, ErrNotFound) {
		t.Fatalf("update deleted comment error = %v", err)
	}
	count, err := repository.Count(ctx, "workspace-1", "doc-1")
	if err != nil || count != 0 {
		t.Fatalf("live comment count = %d, %v; want 0", count, err)
	}
	changes, err := repository.ListChanges(ctx, "workspace-1", "doc-1", nil, nil, 10)
	if err != nil || len(changes) != 2 || changes[0].Action != "delete" || changes[1].Action != "delete" {
		t.Fatalf("comment and reply tombstones = %#v, %v", changes, err)
	}

	lockTx, err := pool.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	lockKey := "workspace-doc-update:workspace-1/doc-1"
	if _, err := lockTx.Exec(ctx, `SELECT pg_advisory_xact_lock(hashtextextended($1,0))`, lockKey); err != nil {
		_ = lockTx.Rollback(ctx)
		t.Fatalf("acquire document lifecycle lock: %v", err)
	}
	type createResult struct {
		comment Comment
		err     error
	}
	created := make(chan createResult, 1)
	go func() {
		comment, err := repository.CreateComment(ctx, "author-1", "workspace-1", "doc-1", map[string]any{"text": "after lifecycle"}, NotificationInput{})
		created <- createResult{comment: comment, err: err}
	}()
	select {
	case result := <-created:
		_ = lockTx.Rollback(ctx)
		t.Fatalf("comment create passed the held document lifecycle lock: %+v, %v", result.comment, result.err)
	case <-time.After(100 * time.Millisecond):
	}
	if err := lockTx.Commit(ctx); err != nil {
		t.Fatalf("release document lifecycle lock: %v", err)
	}
	select {
	case result := <-created:
		if result.err != nil || result.comment.ID == "" {
			t.Fatalf("comment create after lifecycle lock release = %+v, %v", result.comment, result.err)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("comment create stayed blocked after document lifecycle lock release")
	}
}

