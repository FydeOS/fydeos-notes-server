type imageTestTargets struct {
	provider, base, source string
	quota                  *imageTestQuota
	localCalls             *atomic.Int32
}

type imageTestQuota struct {
	reserved int
	released int
}

func (q *imageTestQuota) ReserveCloudImageQuota(context.Context, string, string, string, string, string, string) (string, error) {
	q.reserved++
	return "image-quota-reservation", nil
}

func (q *imageTestQuota) ReleaseCloudImageQuota(context.Context, string) error {
	q.released++
	return nil
}

func (s imageTestTargets) ResolveImageTarget(_ context.Context, workspace, actor, profile, model, operation string) (byok.ChatTarget, error) {
	if workspace != "workspace-1" || actor != "user-1" || profile != "profile-1" || model != "image-model" || (operation != "image_edit" && operation != "image_generate" && operation != "image_process") {
		return byok.ChatTarget{}, byok.ErrTargetUnavailable
	}
	source := s.source
	if source == "" {
		source = "byok_server"
	}
	return byok.ChatTarget{Source: source, Provider: s.provider, ModelID: model, BaseURL: s.base, Credential: byok.NewSensitiveCredential([]byte("image-test-key")), Transport: http.DefaultTransport}, nil
}

func (s imageTestTargets) ResolveLocalImageTarget(_ context.Context, workspace, actor, lease, profile, model, operation string) (byok.ChatTarget, error) {
	if workspace != "workspace-1" || actor != "user-1" || lease != "lease-1" || profile != "lease-1:0" || model != "image-model" || (operation != "image_edit" && operation != "image_generate" && operation != "image_process") {
		return byok.ChatTarget{}, byok.ErrTargetUnavailable
	}
	if s.localCalls != nil {
		s.localCalls.Add(1)
	}
	return byok.ChatTarget{Source: "byok_local", Provider: s.provider, ModelID: model, BaseURL: s.base, Credential: byok.NewSensitiveCredential([]byte("image-test-key")), Transport: http.DefaultTransport}, nil
}

func (s imageTestTargets) ReserveCloudImageQuota(ctx context.Context, userID, workspaceID, sessionID, billingUnitID, provider, model string) (string, error) {
	return s.quota.ReserveCloudImageQuota(ctx, userID, workspaceID, sessionID, billingUnitID, provider, model)
}

func (s imageTestTargets) ReleaseCloudImageQuota(ctx context.Context, reservationID string) error {
	return s.quota.ReleaseCloudImageQuota(ctx, reservationID)
}

func testImageFilterActions(t *testing.T, pool *pgxpool.Pool, store *Store) {
	t.Helper()
	ctx := context.Background()
	if _, err := pool.Exec(ctx, `ALTER TABLE ai_prompts_metadata ADD COLUMN config json DEFAULT '{}'; INSERT INTO ai_prompts_metadata(id,name,config) VALUES(11,'image.filter.sketch','{"modelName":"base-model","loras":[{"path":"style"}]}'),(12,'image.filter.clay','{}'),(13,'image.filter.anime','{}'),(14,'image.filter.pixel','{}'),(15,'Generate image','{"quality":"high"}'),(16,'Upscale image','{}'); INSERT INTO ai_prompts_messages(prompt_id,idx,role,content) VALUES(11,0,'user','{{content}} sketch'),(12,0,'user','{{content}} clay'),(13,0,'user','{{content}} anime'),(14,0,'user','{{content}} pixel'),(15,0,'user','{{content}}'),(16,0,'user','{{content}}')`); err != nil {
		t.Fatal(err)
	}
	var generated bytes.Buffer
	pic := image.NewRGBA(image.Rect(0, 0, 2, 2))
	pic.Set(0, 0, color.RGBA{R: 255, A: 255})
	if err := png.Encode(&generated, pic); err != nil {
		t.Fatal(err)
	}
	encoded := base64.StdEncoding.EncodeToString(generated.Bytes())
	var deny atomic.Bool
	authorize := func(context.Context, string, string, *string) error {
		if deny.Load() {
			return errors.New("denied")
		}
		return nil
	}
	objects := &attachmentObjects{}
	attachments := NewSessionAttachments(objects, store, authorize, attachmentAuthenticator{userID: "user-1"}, nil)
	inputURL, err := attachments.Upload(ctx, "user-1", "session-1", "input.png", "image/png", bytes.NewReader(generated.Bytes()))
	if err != nil {
		t.Fatal(err)
	}
	inputs, _ := json.Marshal([]string{inputURL})
	if _, err := pool.Exec(ctx, `UPDATE ai_sessions_messages SET attachments=$1 WHERE id='message-1'`, inputs); err != nil {
		t.Fatal(err)
	}
	imageUsageExpected := 0
	for _, providerName := range []string{"openai", "gemini", "fal"} {
		t.Run("image_"+providerName, func(t *testing.T) {
			var fail, invalid, revoke atomic.Bool
			var blockProvider atomic.Bool
			var calls atomic.Int32
			entered := make(chan struct{}, 1)
			releaseProvider := make(chan struct{}, 1)
			provider := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				calls.Add(1)
				if blockProvider.Load() {
					entered <- struct{}{}
					select {
					case <-r.Context().Done():
					case <-releaseProvider:
					}
					return
				}
				if fail.Load() {
					http.Error(w, "provider secret diagnostic", 502)
					return
				}
				if revoke.Load() {
					deny.Store(true)
				}
				switch providerName {
				case "openai":
					if r.URL.Path == "/images/generations" {
						var request map[string]any
						if json.NewDecoder(r.Body).Decode(&request) != nil || request["model"] != "image-model" || request["n"] != float64(1) || request["quality"] != "high" {
							t.Errorf("invalid generation request: %v", request)
						}
						_ = json.NewEncoder(w).Encode(map[string]any{"data": []any{map[string]string{"b64_json": encoded}}})
						return
					}
					if r.URL.Path != "/images/edits" || r.Header.Get("Authorization") != "Bearer image-test-key" {
						t.Errorf("incorrect OpenAI path or credential")
					}
					if err := r.ParseMultipartForm(1 << 20); err != nil {
						t.Error(err)
						return
					}
					defer r.MultipartForm.RemoveAll()
					parts := r.MultipartForm.File["image[]"]
					if len(parts) != 1 || parts[0].Header.Get("Content-Type") != "image/png" || r.FormValue("model") != "image-model" {
						t.Errorf("invalid OpenAI input")
						return
					}
					file, err := parts[0].Open()
					if err != nil {
						t.Error(err)
						return
					}
					data, _ := io.ReadAll(file)
					file.Close()
					if !bytes.Equal(data, generated.Bytes()) {
						t.Error("OpenAI input bytes changed")
					}
					output := encoded
					if invalid.Load() {
						output = base64.StdEncoding.EncodeToString([]byte("not an image"))
					}
					_ = json.NewEncoder(w).Encode(map[string]any{"data": []any{map[string]string{"b64_json": output}}})
				case "gemini":
					if r.URL.Path != "/models/image-model:generateContent" || r.Header.Get("x-goog-api-key") != "image-test-key" {
						t.Error("incorrect Gemini path or credential")
					}
					var req struct {
						Contents []struct {
							Parts []struct {
								InlineData struct {
									Data string `json:"data"`
								} `json:"inlineData"`
							} `json:"parts"`
						} `json:"contents"`
					}
					if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
						t.Error(err)
						return
					}
					if len(req.Contents) != 1 || (len(req.Contents[0].Parts) != 1 && (len(req.Contents[0].Parts) != 2 || req.Contents[0].Parts[1].InlineData.Data != encoded)) {
						t.Error("Gemini input missing")
					}
					reason := "STOP"
					if invalid.Load() {
						reason = "SAFETY"
					}
					_ = json.NewEncoder(w).Encode(map[string]any{"candidates": []any{map[string]any{"finishReason": reason, "content": map[string]any{"parts": []any{map[string]any{"inlineData": map[string]string{"data": encoded, "mimeType": "image/png"}}}}}}})
				case "fal":
					if r.URL.Path != "/fal-ai/image-model" || r.Header.Get("Authorization") != "Key image-test-key" {
						t.Error("incorrect FAL path or credential")
					}
					var req map[string]any
					if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
						t.Error(err)
						return
					}
					if req["sync_mode"] != true {
						t.Error("FAL input missing")
					}
					if strings.Contains(req["prompt"].(string), "sketch") && (req["model_name"] != "base-model" || req["loras"] == nil) {
						t.Error("FAL style config missing")
					}
					locator := "data:image/png;base64," + encoded
					if invalid.Load() {
						locator = "http://127.0.0.1/private"
					}
					_ = json.NewEncoder(w).Encode(map[string]any{"images": []any{map[string]string{"url": locator}}})
				}
			}))
			defer provider.Close()
			handler := NewChatHTTPHandler(pool, config.Config{FydeOSManagedCopilot: true}, chatTestAuthenticator{principal: &auth.Principal{User: auth.User{ID: "user-1"}}}, store, authorize, chatTestFeature{enabled: true})
			handler.SetSessionAttachments(attachments)
			handler.SetImageTargetResolver(imageTestTargets{provider: providerName, base: provider.URL})
			serveTarget := func(action, target, extra string) *httptest.ResponseRecorder {
				r := httptest.NewRequest("GET", "/api/copilot/actions/session-1/stream?messageId=message-1&actionId="+action+"&routeTargetId="+target+extra, nil)
				r.SetPathValue("sessionId", "session-1")
				w := httptest.NewRecorder()
				handler.ActionHandler().ServeHTTP(w, r)
				return w
			}
			serve := func(action, extra string) *httptest.ResponseRecorder {
				return serveTarget(action, "fydeos-byok:profile-1:image-model", extra)
			}
			if _, err := pool.Exec(ctx, `UPDATE ai_sessions_metadata SET prompt_name='Chat With AFFiNE AI' WHERE id='session-1'`); err != nil {
				t.Fatal(err)
			}
			if _, err := pool.Exec(ctx, `UPDATE ai_sessions_messages SET attachments=$1 WHERE id='message-1'`, inputs); err != nil {
				t.Fatal(err)
			}
			imageUsageExpected += 5
			for _, style := range []string{"sketch", "clay", "anime", "pixel"} {
				action := "image.filter." + style
				response := serve(action, "")
				if response.Code != 200 || !strings.Contains(response.Body.String(), "event: attachment") || !strings.Contains(response.Body.String(), `"type":"action_done"`) {
					t.Fatalf("image action failed: %d %s", response.Code, response.Body.String())
				}

				// The current image UI passes attachment data directly to fetch.
				// It must be an unquoted locator, not JSON artifact metadata.
				attachmentData := ""
				for _, event := range strings.Split(response.Body.String(), "\n\n") {
					if strings.HasPrefix(event, "event: attachment\n") {
						for _, line := range strings.Split(event, "\n") {
							if strings.HasPrefix(line, "data: ") {
								attachmentData = strings.TrimPrefix(line, "data: ")
							}
						}
					}
				}
				if !strings.HasPrefix(attachmentData, "/api/copilot/chat/session-1/attachments/") {
					t.Fatalf("attachment is not a directly fetchable locator: %q", attachmentData)
				}
				var artifact struct {
					URL  string `json:"url"`
					MIME string `json:"mimeType"`
				}
				var result []byte
				var runID, assistantID string
				if err := pool.QueryRow(ctx, `SELECT id,result,assistant_message_id FROM ai_action_runs WHERE action_id=$1 AND status='succeeded' ORDER BY created_at DESC LIMIT 1`, action).Scan(&runID, &result, &assistantID); err != nil {
					t.Fatal(err)
				}
				if err := json.Unmarshal(result, &artifact); err != nil {
					t.Fatal(err)
				}
				if artifact.MIME != "image/png" || artifact.URL == "" {
					t.Fatalf("artifact=%+v", artifact)
				}
				var refs []byte
				if err := pool.QueryRow(ctx, `SELECT attachments FROM ai_sessions_messages WHERE id=$1 AND role='assistant'`, assistantID).Scan(&refs); err != nil || !bytes.Contains(refs, []byte("/api/copilot/chat/session-1/attachments/")) {
					t.Fatalf("assistant refs=%s err=%v", refs, err)
				}
				var usage int
				if err := pool.QueryRow(ctx, `SELECT count(*) FROM ai_usage_events WHERE billing_unit_id=$1 AND feature_kind='image' AND provider_source='byok_server'`, runID).Scan(&usage); err != nil || usage != 1 {
					t.Fatalf("usage=%d err=%v", usage, err)
				}
				r := httptest.NewRequest("GET", artifact.URL, nil)
				r.SetPathValue("sessionId", "session-1")
				r.SetPathValue("key", strings.Split(r.URL.Path, "/")[6])
				w := httptest.NewRecorder()
				attachments.ServeHTTP(w, r)
				if w.Code != 200 || !bytes.Equal(w.Body.Bytes(), generated.Bytes()) {
					t.Fatalf("image download=%d %s", w.Code, w.Body.String())
				}
				other := NewSessionAttachments(objects, store, authorize, attachmentAuthenticator{userID: "user-2"}, nil)
				w = httptest.NewRecorder()
				other.ServeHTTP(w, r)
				if w.Code == 200 {
					t.Fatal("foreign user downloaded image")
				}
			}
			quota := &imageTestQuota{}
			handler.SetImageTargetResolver(imageTestTargets{provider: providerName, base: provider.URL, source: "affine_cloud", quota: quota})
			managedResponse := serve("image.filter.sketch", "")
			if managedResponse.Code != 200 || quota.reserved != 1 || quota.released != 1 {
				t.Fatalf("managed image action quota reservation did not settle: status=%d reserved=%d released=%d body=%s", managedResponse.Code, quota.reserved, quota.released, managedResponse.Body.String())
			}
			actionLocalCalls := &atomic.Int32{}
			handler.SetImageTargetResolver(imageTestTargets{provider: providerName, base: provider.URL, localCalls: actionLocalCalls})
			localResponse := serveTarget("image.filter.sketch", "fydeos-byok:lease-1:0:image-model", "&byokLeaseId=lease-1")
			if localResponse.Code != 200 || actionLocalCalls.Load() != 1 || !strings.Contains(localResponse.Body.String(), "event: attachment") {
				t.Fatalf("local image action failed: status=%d resolverCalls=%d body=%s", localResponse.Code, actionLocalCalls.Load(), localResponse.Body.String())
			}
			var localUsage int
			if err := pool.QueryRow(ctx, `SELECT count(*) FROM ai_action_runs run JOIN ai_usage_events usage ON usage.billing_unit_id=run.id WHERE run.action_id='image.filter.sketch' AND run.status='succeeded' AND usage.provider=$1 AND usage.provider_source='byok_local' AND usage.feature_kind='image'`, providerName).Scan(&localUsage); err != nil || localUsage != 1 {
				t.Fatalf("local image action usage=%d err=%v", localUsage, err)
			}
			handler.SetImageTargetResolver(imageTestTargets{provider: providerName, base: provider.URL})
			fail.Store(true)
			response := serve("image.filter.sketch", "")
			if !strings.Contains(response.Body.String(), "The image provider request failed") || strings.Contains(response.Body.String(), "secret diagnostic") {
				t.Fatalf("failure=%s", response.Body.String())
			}
			var failedID string
			if err := pool.QueryRow(ctx, `SELECT id FROM ai_action_runs WHERE action_id='image.filter.sketch' AND status='failed' ORDER BY created_at DESC LIMIT 1`).Scan(&failedID); err != nil {
				t.Fatal(err)
			}
			fail.Store(false)
			response = serve("image.filter.sketch", "&retry=true&runId="+url.QueryEscape(failedID))
			if !strings.Contains(response.Body.String(), `"type":"action_done"`) {
				t.Fatalf("retry=%s", response.Body.String())
			}
			var attempt int
			if err := pool.QueryRow(ctx, `SELECT attempt FROM ai_action_runs WHERE retry_of=$1 AND status='succeeded'`, failedID).Scan(&attempt); err != nil || attempt != 2 {
				t.Fatalf("retry attempt=%d err=%v", attempt, err)
			}
			invalid.Store(true)
			response = serve("image.filter.sketch", "")
			if !strings.Contains(response.Body.String(), "The image provider request failed") || strings.Contains(response.Body.String(), "event: attachment") {
				t.Fatalf("invalid image=%s", response.Body.String())
			}
			invalid.Store(false)
			deny.Store(true)
			before := calls.Load()
			response = serve("image.filter.sketch", "")
			deny.Store(false)
			if calls.Load() != before || !strings.Contains(response.Body.String(), "Copilot access is denied") {
				t.Fatalf("denied=%s", response.Body.String())
			}
			revoke.Store(true)
			response = serve("image.filter.sketch", "")
			revoke.Store(false)
			deny.Store(false)
			if !strings.Contains(response.Body.String(), "The generated image could not be saved") || strings.Contains(response.Body.String(), "event: attachment") {
				t.Fatalf("revoked=%s", response.Body.String())
			}

			// A request that passed admission can lose access while waiting for
			// capacity. Data URLs intentionally avoid the storage ACL path.
			dataInputs, _ := json.Marshal([]string{"data:image/png;base64," + encoded})
			if _, err := pool.Exec(ctx, `UPDATE ai_sessions_messages SET attachments=$1 WHERE id='message-1'`, dataInputs); err != nil {
				t.Fatal(err)
			}
			admitted := make(chan struct{}, 1)
			handler.authorize = func(ctx context.Context, u, w string, d *string) error {
				err := authorize(ctx, u, w, d)
				select {
				case admitted <- struct{}{}:
				default:
				}
				return err
			}
			handler.imageGate <- struct{}{}
			handler.imageGate <- struct{}{}
			completed := make(chan *httptest.ResponseRecorder, 1)
			before = calls.Load()
			go func() { completed <- serve("image.filter.sketch", "") }()
			select {
			case <-admitted:
			case <-time.After(2 * time.Second):
				t.Fatal("request did not reach admission")
			}
			deny.Store(true)
			<-handler.imageGate
			select {
			case response = <-completed:
			case <-time.After(2 * time.Second):
				t.Fatal("queued request did not complete")
			}
			<-handler.imageGate
			deny.Store(false)
			handler.authorize = authorize
			if _, err := pool.Exec(ctx, `UPDATE ai_sessions_messages SET attachments=$1 WHERE id='message-1'`, inputs); err != nil {
				t.Fatal(err)
			}
			if calls.Load() != before {
				t.Fatal("queued revoked request called image provider")
			}
			var leaked int
			if err := pool.QueryRow(ctx, `SELECT count(*) FROM ai_action_runs r LEFT JOIN ai_usage_events u ON u.billing_unit_id=r.id WHERE r.action_id LIKE 'image.%' AND r.status='failed' AND (r.assistant_message_id IS NOT NULL OR u.id IS NOT NULL)`).Scan(&leaked); err != nil || leaked != 0 {
				t.Fatalf("failed run leaked result/usage=%d err=%v", leaked, err)
			}
			if _, err := pool.Exec(ctx, `UPDATE ai_sessions_metadata SET prompt_name='Generate image' WHERE id='session-1'; UPDATE ai_sessions_messages SET attachments='[]' WHERE id='message-1'`); err != nil {
				t.Fatal(err)
			}
			beforeGeneration := calls.Load()
			request := httptest.NewRequest("GET", "/api/copilot/chat/session-1/images?messageId=message-1&seed=42&routeTargetId=fydeos-byok:profile-1:image-model", nil)
			request.SetPathValue("sessionId", "session-1")
			request.SetPathValue("endpoint", "images")
			response = httptest.NewRecorder()
			handler.ServeHTTP(response, request)
			if response.Code != 200 || !strings.Contains(response.Body.String(), "event: attachment") || !strings.Contains(response.Body.String(), "/api/copilot/chat/session-1/attachments/") {
				t.Fatalf("image generation failed: %d %s", response.Code, response.Body.String())
			}
			var content string
			var saved []byte
			if err := pool.QueryRow(ctx, `SELECT content,attachments FROM ai_sessions_messages WHERE session_id='session-1' AND role='assistant' ORDER BY created_at DESC LIMIT 1`).Scan(&content, &saved); err != nil || content != "" || !strings.Contains(string(saved), "/api/copilot/chat/session-1/attachments/") {
				t.Fatalf("image turn content=%q attachments=%s err=%v", content, saved, err)
			}
			imageUsageExpected++
			if err := pool.QueryRow(ctx, `SELECT count(*) FROM ai_usage_events WHERE provider_source='byok_server' AND feature_kind='image'`).Scan(&leaked); err != nil || leaked != imageUsageExpected {
				t.Fatalf("image usage=%d want=%d err=%v", leaked, imageUsageExpected, err)
			}
			if providerName == "openai" {
				if _, err := pool.Exec(ctx, `UPDATE ai_sessions_metadata SET prompt_name='Upscale image' WHERE id='session-1'`); err != nil {
					t.Fatal(err)
				}
				if _, err := pool.Exec(ctx, `UPDATE ai_sessions_messages SET attachments=$1 WHERE id='message-1'`, inputs); err != nil {
					t.Fatal(err)
				}
				request = httptest.NewRequest("GET", "/api/copilot/chat/session-1/images?messageId=message-1&routeTargetId=fydeos-byok:profile-1:image-model", nil)
				request.SetPathValue("sessionId", "session-1")
				request.SetPathValue("endpoint", "images")
				response = httptest.NewRecorder()
				handler.ServeHTTP(response, request)
				if response.Code != 200 || !strings.Contains(response.Body.String(), "event: attachment") || calls.Load() != beforeGeneration+2 {
					t.Fatalf("image processing failed: %d calls=%d %s", response.Code, calls.Load(), response.Body.String())
				}
				imageUsageExpected++
				beforeAssistant := 0
				if err := pool.QueryRow(ctx, `SELECT count(*) FROM ai_sessions_messages WHERE session_id='session-1' AND role='assistant'`).Scan(&beforeAssistant); err != nil {
					t.Fatal(err)
				}
				blockProvider.Store(true)
				cancelCtx, cancel := context.WithCancel(context.Background())
				request = httptest.NewRequest("GET", "/api/copilot/chat/session-1/images?messageId=message-1&routeTargetId=fydeos-byok:profile-1:image-model", nil).WithContext(cancelCtx)
				request.SetPathValue("sessionId", "session-1")
				request.SetPathValue("endpoint", "images")
				finished := make(chan *httptest.ResponseRecorder, 1)
				go func() { recorder := httptest.NewRecorder(); handler.ServeHTTP(recorder, request); finished <- recorder }()
				select {
				case <-entered:
				case <-time.After(2 * time.Second):
					t.Fatal("image request did not reach provider")
				}
				cancel()
				releaseProvider <- struct{}{}
				select {
				case response = <-finished:
				case <-time.After(2 * time.Second):
					t.Fatal("cancelled image request did not stop")
				}
				blockProvider.Store(false)
				cancel()
				if strings.Contains(response.Body.String(), "event: attachment") {
					t.Fatalf("cancelled image request emitted attachment: %s", response.Body.String())
				}
				var afterAssistant int
				if err := pool.QueryRow(ctx, `SELECT count(*) FROM ai_sessions_messages WHERE session_id='session-1' AND role='assistant'`).Scan(&afterAssistant); err != nil || afterAssistant != beforeAssistant {
					t.Fatalf("cancelled image assistant rows=%d before=%d err=%v", afterAssistant, beforeAssistant, err)
				}
			}
			if err := pool.QueryRow(ctx, `SELECT count(*) FROM ai_usage_events WHERE provider_source='byok_server' AND feature_kind='image'`).Scan(&leaked); err != nil || leaked != imageUsageExpected {
				t.Fatalf("image usage=%d want=%d err=%v", leaked, imageUsageExpected, err)
			}
			generationLocalCalls := &atomic.Int32{}
			handler.SetImageTargetResolver(imageTestTargets{provider: providerName, base: provider.URL, localCalls: generationLocalCalls})
			localRequest := httptest.NewRequest("GET", "/api/copilot/chat/session-1/images?messageId=message-1&byokLeaseId=lease-1&routeTargetId=fydeos-byok%3Alease-1%3A0%3Aimage-model", nil)
			localRequest.SetPathValue("sessionId", "session-1")
			localRequest.SetPathValue("endpoint", "images")
			generationLocalResponse := httptest.NewRecorder()
			handler.ServeHTTP(generationLocalResponse, localRequest)
			if generationLocalResponse.Code != 200 || generationLocalCalls.Load() != 1 || !strings.Contains(generationLocalResponse.Body.String(), "event: attachment") {
				t.Fatalf("local image route failed: status=%d resolverCalls=%d body=%s", generationLocalResponse.Code, generationLocalCalls.Load(), generationLocalResponse.Body.String())
			}
			var generationLocalUsage int
			if err := pool.QueryRow(ctx, `SELECT count(*) FROM ai_usage_events WHERE provider=$1 AND provider_source='byok_local' AND feature_kind='image'`, providerName).Scan(&generationLocalUsage); err != nil || generationLocalUsage != 2 {
				t.Fatalf("local image usage=%d err=%v", generationLocalUsage, err)
			}
		})
	}
}

